"""Create a minimal, reproducible int32-axis patch for the pinned BPSD graph.

No learned tensor is modified. ONNX permits int32 or int64 CumSum axes; ORT
1.23.2's native WebGPU/CPU boundary mishandles the latter in this export.
Run with the locked tools/gliner-onnx environment from the repository root.
"""
import hashlib, json
from pathlib import Path
import numpy as np
import onnx
import onnxruntime as ort
from onnx import numpy_helper

ROOT=Path(__file__).resolve().parents[2]
folder=next((ROOT/'work/final-r2-bpsd').iterdir())
source=(folder/'attributes.onnx').read_bytes()
assert hashlib.sha256(source).hexdigest()=='ac37764700eabbb6ccd1fd95cdc8041836439a86dbf98ecf1c913cc67281909c'

def varint(value):
    out=bytearray()
    while value>127:out.append((value&127)|128);value>>=7
    out.append(value);return bytes(out)

def read_varint(data,at):
    value=0;shift=0
    while True:
        byte=data[at];at+=1;value|=(byte&127)<<shift
        if byte<128:return value,at
        shift+=7

def fields(data):
    at=0
    while at<len(data):
        start=at;tag,at=read_varint(data,at);size_at=at
        if tag&7==2:size,at=read_varint(data,at);body=at;at+=size
        elif tag&7==0:_,at=read_varint(data,at);body=size_at
        elif tag&7==1:body=at;at+=8
        elif tag&7==5:body=at;at+=4
        else:raise ValueError('Unsupported protobuf wire type')
        yield tag>>3,start,size_at,body,at

def message(number,data):return varint((number<<3)|2)+varint(len(data))+data

graph=next(f for f in fields(source) if f[0]==7)
_,_,size_at,body,end=graph
patches=[]
for number,start,_,node_body,node_end in fields(source[body:end]):
    if number!=1:continue
    node=onnx.NodeProto();node.ParseFromString(source[body+node_body:body+node_end])
    if node.op_type!='CumSum':continue
    axis={'node_CumSum_741':-1,'node_CumSum_1108':1}[node.name]
    name=node.name+'_axis_int32'
    node.input[1]=name
    initializer=numpy_helper.from_array(np.array(axis,dtype=np.int32),name)
    replacement=message(1,node.SerializeToString())+message(5,initializer.SerializeToString())
    patches.append({'offset':body+start,'before':source[body+start:body+node_end].hex(),'after':replacement.hex()})
assert len(patches)==2
delta=sum((len(p['after'])-len(p['before']))//2 for p in patches)
patches.append({'offset':size_at,'before':source[size_at:body].hex(),'after':varint(end-body+delta).hex()})
patched=source
for patch in sorted(patches,key=lambda p:p['offset'],reverse=True):
    at=patch['offset'];before=bytes.fromhex(patch['before']);assert patched[at:at+len(before)]==before
    patched=patched[:at]+bytes.fromhex(patch['after'])+patched[at+len(before):]
model=onnx.load_from_string(patched);onnx.checker.check_model(model,full_check=True)
original=onnx.load_from_string(source)
before_weights={tensor.name:tensor.SerializeToString() for tensor in original.graph.initializer}
after_weights={tensor.name:tensor.SerializeToString() for tensor in model.graph.initializer}
assert all(after_weights[name]==value for name,value in before_weights.items())
assert set(after_weights)-set(before_weights)=={'node_CumSum_741_axis_int32','node_CumSum_1108_axis_int32'}
fixture=json.loads((folder/'attributes-reference.json').read_text())
feeds={name:np.array(value['data'],dtype=value['type']).reshape(value['dims']) for name,value in fixture['feeds'].items()}
options=ort.SessionOptions();options.log_severity_level=3
old=ort.InferenceSession(source,options,providers=['CPUExecutionProvider']).run(None,feeds)[0]
new=ort.InferenceSession(patched,options,providers=['CPUExecutionProvider']).run(None,feeds)[0]
assert np.array_equal(old,new),'Axis conversion changed native attribute logits'
out=ROOT/'temp/browser-validation/webgpu';out.mkdir(parents=True,exist_ok=True)
(out/'bpsd-attributes-int32.onnx').write_bytes(patched)
record={'id':'bpsd-cumsum-axis-int32-v1','sourceSha256':hashlib.sha256(source).hexdigest(),'targetSha256':hashlib.sha256(patched).hexdigest(),'patches':sorted(patches,key=lambda p:p['offset'])}
(out/'axis-patch.json').write_text(json.dumps(record,indent=2))
(ROOT/'src/nextmedtator/webgpu-axis-patch.mjs').write_text('// Generated by tools/gliner-onnx/qualify_webgpu_axes.py. No learned weights.\nexport const AXIS_PATCH = '+json.dumps(record,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps({'sourceSha256':record['sourceSha256'],'targetSha256':record['targetSha256'],'nativeFixtureBitExact':True,'patchBytes':sum(len(p['after'])//2 for p in patches)},indent=2))
